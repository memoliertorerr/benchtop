/**
 * The offline app shell's file list (BT40), computed at build time from Vite's output bundle:
 * the HTML page, every entry chunk with its static imports and CSS, the simulation worker,
 * and the static files the page links (icon, web app manifest). Everything else — part view
 * chunks, example projects and firmware — the service worker caches the first time it's
 * fetched. Pure, so the build plugin in vite.config.ts and a Node test share it.
 */

/** The parts of a Rollup output entry this needs (chunks and assets). */
export interface BundleEntry {
  type: 'chunk' | 'asset';
  fileName: string;
  isEntry?: boolean;
  imports?: readonly string[];
  viteMetadata?: { importedCss: ReadonlySet<string> };
}

/** Files served from `public/` that the page links directly. */
export const STATIC_SHELL = ['/index.html', '/favicon.svg', '/manifest.webmanifest'] as const;

/** The shell's URL paths, sorted. */
export function shellFiles(bundle: Readonly<Record<string, BundleEntry>>): string[] {
  const files = new Set<string>(STATIC_SHELL);
  const visit = (name: string): void => {
    const path = `/${name}`;
    if (files.has(path)) return;
    files.add(path);
    const entry = bundle[name];
    if (entry?.type !== 'chunk') return;
    for (const imported of entry.imports ?? []) visit(imported);
    for (const css of entry.viteMetadata?.importedCss ?? []) files.add(`/${css}`);
  };
  for (const entry of Object.values(bundle)) {
    if (entry.type === 'chunk' && entry.isEntry === true) visit(entry.fileName);
    // The worker is an asset of the page's build (Vite bundles it on its own).
    if (entry.type === 'asset' && /(^|\/)worker-[\w-]+\.js$/.test(entry.fileName)) files.add(`/${entry.fileName}`);
    if (entry.type === 'asset' && entry.fileName.endsWith('.css')) files.add(`/${entry.fileName}`);
  }
  return [...files].sort();
}

/** A short version tag for a file list: hashed file names change whenever their content does. */
export function shellVersion(files: readonly string[]): string {
  // FNV-1a, 32 bits, twice with different seeds: no crypto needed for a cache name.
  let a = 0x811c9dc5;
  let b = 0x01000193 ^ 0x5bd1e995;
  for (const file of files) {
    for (let i = 0; i < file.length; i++) {
      const c = file.charCodeAt(i);
      a = Math.imul(a ^ c, 0x01000193) >>> 0;
      b = Math.imul(b ^ c, 0x01000193) >>> 0;
    }
    a = Math.imul(a ^ 10, 0x01000193) >>> 0;
    b = Math.imul(b ^ 13, 0x01000193) >>> 0;
  }
  return a.toString(16).padStart(8, '0') + b.toString(16).padStart(8, '0');
}

/** The script the service worker imports (`/sw-precache.js`): the version and the file list. */
export function precacheScript(files: readonly string[]): string {
  return `// Generated by the build (apps/web/src/offline/shell.ts): the offline app shell.\nself.BENCHTOP_SHELL = ${JSON.stringify({ version: shellVersion(files), files })};\n`;
}
