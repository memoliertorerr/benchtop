/**
 * The Xtensa LX6 opcode table for the ESP32 configuration: every instruction the local
 * xtensa-esp32-elf-objdump decodes (the base ISA, Code Density, MAC16, the FPU, booleans, the
 * TLB/region ops, Espressif's TIE extensions such as the f64* double-precision helpers,
 * *_expstate and lddr32.p/sddr32.p). Each row is `[mnemonic, length, mask, match, immediate kind,
 * operands]`: a word is this instruction when `(word & mask) === match`; the operands are listed
 * in objdump's print order.
 *
 * Encodings follow the opcode tables of the Xtensa ISA Reference Manual and the ESP32 core-isa.h
 * and tie.h; the masks were cross-checked against objdump by flipping each bit of a known
 * encoding (which bits change the mnemonic, which change which operand), never read from
 * binutils' sources. The differential test (decode.test.ts) checks every corpus line. Special
 * and user registers are part of the mnemonic (`rsr.ps`, `rur.threadptr`), as objdump prints
 * them; encodings it has no name for are invalid.
 *
 * Operand kinds: A/F/B + R/S/T = a register of that file from the r, s or t field; B4/B8 = a
 * boolean group from s (`b4:b5:b6:b7`); MW = m(r & 3), MX = m((r >> 2) & 1), MY = m(2 + ((t >> 2) & 1))
 * (MAC16); IMM/IMM2 = the descriptor's immediates; TGT = the branch, jump, call, loop or l32r
 * target. Immediate kinds are computed in decode.ts.
 */

