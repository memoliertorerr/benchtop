/**
 * Opcode ids and per-op metadata shared by decode.ts, disasm.ts and the CPU. `OP.X` is the row
 * index of mnemonic x in OP_TABLE (isa-table.ts), with '.' and other punctuation as '_'
 * (`OP.ADD_N`, `OP.RSR_PS`, `OP.MULA_DD_LL_LDINC`). OP_INVALID marks an encoding that decodes to
 * no instruction.
 */

