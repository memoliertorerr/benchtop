/**
 * Generates packages/rp2350/src/periph/reg-defaults.generated.ts: the reset value of every RP2350
 * peripheral register the pico-sdk headers describe (`#define <PREFIX>_<REG>_OFFSET _u(0x…)` with
 * its `#define <PREFIX>_<REG>_RESET _u(0x…)`), as offset → value per block base, for the nonzero
 * ones. Run by hand when the headers change:
 *   node scripts/gen-rp2350-reg-defaults.ts
 * Source: the installed arduino-pico core's pico-sdk (BSD-3-Clause, Raspberry Pi),
 * src/rp2350/hardware_regs/include/hardware/regs/<name>.h.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CORES = join(homedir(), 'Library/Arduino15/packages/rp2040/hardware/rp2040');
const VERSION = readdirSync(CORES).sort().at(-1) as string;
const REGS = join(CORES, VERSION, 'pico-sdk/src/rp2350/hardware_regs/include/hardware/regs');
const OUT = join(ROOT, 'packages/rp2350/src/periph/reg-defaults.generated.ts');

/** Header, its macros' prefix, the block bases it describes. */
const BLOCKS: [string, string, number[]][] = [
  ['sysinfo.h', 'SYSINFO_', [0x40000000]],
  ['syscfg.h', 'SYSCFG_', [0x40008000]],
  ['clocks.h', 'CLOCKS_', [0x40010000]],
  ['psm.h', 'PSM_', [0x40018000]],
  ['resets.h', 'RESETS_', [0x40020000]],
  ['io_bank0.h', 'IO_BANK0_', [0x40028000]],
  ['io_qspi.h', 'IO_QSPI_', [0x40030000]],
  ['pads_bank0.h', 'PADS_BANK0_', [0x40038000]],
  ['pads_qspi.h', 'PADS_QSPI_', [0x40040000]],
  ['xosc.h', 'XOSC_', [0x40048000]],
  ['pll.h', 'PLL_', [0x40050000, 0x40058000]],
  ['accessctrl.h', 'ACCESSCTRL_', [0x40060000]],
  ['busctrl.h', 'BUSCTRL_', [0x40068000]],
  ['uart.h', 'UART_', [0x40070000, 0x40078000]],
  ['spi.h', 'SPI_', [0x40080000, 0x40088000]],
  ['i2c.h', 'I2C_', [0x40090000, 0x40098000]],
  ['adc.h', 'ADC_', [0x400a0000]],
  ['pwm.h', 'PWM_', [0x400a8000]],
  ['timer.h', 'TIMER_', [0x400b0000, 0x400b8000]],
  ['hstx_ctrl.h', 'HSTX_CTRL_', [0x400c0000]],
  ['xip.h', 'XIP_', [0x400c8000]],
  ['qmi.h', 'QMI_', [0x400d0000]],
  ['watchdog.h', 'WATCHDOG_', [0x400d8000]],
  ['bootram.h', 'BOOTRAM_', [0x400e0000]],
  ['rosc.h', 'ROSC_', [0x400e8000]],
  ['trng.h', 'TRNG_', [0x400f0000]],
  ['sha256.h', 'SHA256_', [0x400f8000]],
  ['powman.h', 'POWMAN_', [0x40100000]],
  ['ticks.h', 'TICKS_', [0x40108000]],
  ['otp.h', 'OTP_', [0x40120000]],
  ['glitch_detector.h', 'GLITCH_DETECTOR_', [0x40158000]],
  ['tbman.h', 'TBMAN_', [0x40160000]],
  ['dma.h', 'DMA_', [0x50000000]],
  ['usb.h', 'USB_', [0x50110000]],
  ['pio.h', 'PIO_', [0x50200000, 0x50300000, 0x50400000]],
  ['xip_aux.h', 'XIP_AUX_', [0x50500000]],
  ['sio.h', 'SIO_', [0xd0000000]],
];

const lines: string[] = [];
let total = 0;
for (const [header, prefix, bases] of BLOCKS) {
  const text = readFileSync(join(REGS, header), 'utf8');
  const offsets = new Map<string, number>();
  const resets = new Map<string, number>();
  for (const m of text.matchAll(/^#define\s+(\w+)_OFFSET\s+_u\(0x([0-9a-fA-F]+)\)/gm)) if (m[1].startsWith(prefix)) offsets.set(m[1], Number.parseInt(m[2], 16));
  for (const m of text.matchAll(/^#define\s+(\w+)_RESET\s+_u\(0x([0-9a-fA-F]+)\)/gm)) resets.set(m[1], Number.parseInt(m[2], 16));
  const pairs: [number, number][] = [];
  for (const [name, offset] of offsets) {
    const reset = resets.get(name);
    if (reset !== undefined && reset !== 0) pairs.push([offset, reset >>> 0]);
  }
  pairs.sort((a, b) => a[0] - b[0]);
  total += pairs.length;
  const body = pairs.map(([o, v]) => `0x${o.toString(16)}, 0x${v.toString(16)}`).join(', ');
  for (const base of bases) lines.push(`  0x${base.toString(16)}: [${body}], // ${header}`);
}

const out = `/**
 * GENERATED by scripts/gen-rp2350-reg-defaults.ts from the pico-sdk's RP2350 register headers
 * (BSD-3-Clause, Raspberry Pi; arduino-pico ${VERSION}) — do not edit. Per peripheral block base:
 * [offset, reset value, …] for every register whose reset value isn't 0 (${total} registers).
 */

export const REG_DEFAULTS: Readonly<Record<number, readonly number[]>> = {
${lines.join('\n')}
};
`;
writeFileSync(OUT, out);
console.info(`wrote ${OUT}: ${total} nonzero reset values`);
